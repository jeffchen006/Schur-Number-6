"""Generate the paper's vector diagram and table data from the certificates."""
from collections import Counter
import hashlib
import json
from pathlib import Path

here = Path(__file__).resolve().parent
root = here if (here / "certificate.col").exists() else here.parent
out = here / "figures"
out.mkdir(exist_ok=True)
raw = (root / "certificate.col").read_bytes()
tokens = list(map(int, raw.split()))
if tokens[:2] != [537, 6] or len(tokens[2:]) != 537:
    raise ValueError("Unexpected certificate format")
c = [v + 1 for v in tokens[2:]]
if set(c) != set(range(1, 7)):
    raise ValueError("Unexpected colors")
if any(c[x - 1] != c[537 - x] for x in range(1, 538)):
    raise ValueError("The figure requires reflection symmetry")
if any(c[x - 1] == c[y - 1] == c[x + y - 1]
       for x in range(1, 538) for y in range(1, 538 - x)):
    raise ValueError("The certificate is not sum-free")


def permitted(f):
    allowed = set(range(1, 7))
    allowed -= {j for j in range(1, 5) if f < j}
    if f < 38 or 113 < f < 151:
        allowed.discard(5)
    if f < 151:
        allowed.discard(6)
    if f in (38, 236):
        allowed &= {5}
    if f == 151 or f > 236:
        allowed &= {6}
    return allowed


allowed = [permitted(f) for f in range(1, 270)]
if any(c[f - 1] not in allowed[f - 1] for f in range(1, 270)):
    raise ValueError("The certificate violates the displayed frame")


def runs(values):
    result = []
    for x in values:
        if result and result[-1][1] == x - 1:
            result[-1][1] = x
        else:
            result.append([x, x])
    return result


palette = ["0072B2", "E69F00", "009E73", "CC79A7", "D55E00", "333333"]
lines = ["% Generated by make_figures.py from certificate.col; do not edit data by hand."]
for j, color in enumerate(palette, 1):
    lines.append(r"\definecolor{schur" + str(j) + "}{HTML}{" + color + "}")
lines += [r"\begin{tikzpicture}[x=1cm,y=1cm,font=\scriptsize]",
          r"\node[anchor=west,font=\small] at (-0.65,0.43) {(a) The explicit coloring on $[1,537]$};"]
width = 13.1
counts = Counter(c)
for j in range(1, 7):
    y = -(j - 1) * 0.27
    lines.append(fr"\node[anchor=east] at (-0.12,{y + .09:.4f}) {{$C_{j}$}};")
    lines.append(fr"\fill[black!4] (0,{y:.4f}) rectangle ({width},{y + .18:.4f});")
    for lo, hi in runs(x for x in range(1, 538) if c[x - 1] == j):
        left, right = (lo - 1) * width / 537, hi * width / 537
        lines.append(fr"\fill[schur{j}] ({left:.6f},{y:.4f}) rectangle ({right:.6f},{y + .18:.4f});")
    lines.append(fr"\node[anchor=west] at ({width + .12},{y + .09:.4f}) {{{counts[j]}}};")
center = 268.5 * width / 537
lines.append(fr"\draw[black!55,densely dashed] ({center:.6f},.24) -- ({center:.6f},-1.43);")
for x in [1, 100, 200, 300, 400, 500, 537]:
    at = (x - .5) * width / 537
    lines.append(fr"\draw[black!50] ({at:.6f},-1.48) -- ({at:.6f},-1.54);")
    lines.append(fr"\node[anchor=north] at ({at:.6f},-1.55) {{{x}}};")
lines.append(fr"\node[anchor=west] at ({width + .12},-1.73) {{$x$}};")
# Show the forced middle interval under the certificate, without moving data.
left, right = 236 * width / 537, 301 * width / 537
lines.append(fr"\draw[black!60] ({left:.6f},-1.93) -- ({left:.6f},-2.00) -- ({right:.6f},-2.00) -- ({right:.6f},-1.93);")
lines.append(fr"\node[anchor=north] at ({(left + right) / 2:.6f},-2.02) {{$[237,301]\subset C_6$}};")
lines.append(r"\node[anchor=west,font=\small] at (-0.65,-2.70) {(b) Allowed colors in the folded frame, $f=\min(x,538-x)$};")
for j in range(1, 7):
    y = -3.13 - (j - 1) * .27
    lines.append(fr"\node[anchor=east] at (-0.12,{y + .09:.4f}) {{$C_{j}$}};")
    lines.append(fr"\fill[black!4] (0,{y:.4f}) rectangle ({width},{y + .18:.4f});")
    for lo, hi in runs(f for f in range(1, 270) if j in allowed[f - 1]):
        left, right = (lo - 1) * width / 269, hi * width / 269
        lines.append(fr"\fill[schur{j}!35] ({left:.6f},{y:.4f}) rectangle ({right:.6f},{y + .18:.4f});")
    for lo, hi in runs(f for f in range(1, 270) if allowed[f - 1] == {j}):
        left, right = (lo - 1) * width / 269, hi * width / 269
        lines.append(fr"\fill[schur{j}] ({left:.6f},{y:.4f}) rectangle ({right:.6f},{y + .18:.4f});")
for x in [1, 38, 113, 151, 236, 269]:
    at = (x - .5) * width / 269
    lines.append(fr"\draw[black!50] ({at:.6f},-4.61) -- ({at:.6f},-4.67);")
    lines.append(fr"\node[anchor=north] at ({at:.6f},-4.68) {{{x}}};")
lines.append(fr"\node[anchor=west] at ({width + .12},-4.83) {{$f$}};")
lines.append(r"\end{tikzpicture}")
(out / "structure.tex").write_text("\n".join(lines) + "\n")


def renumber(word):
    order = {v: i + 1 for i, v in enumerate(dict.fromkeys(word))}
    return [order[v] for v in word]


families = {}
for line in (root / "solutions537.txt").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    name, word = line.split()
    word = list(map(int, word))
    family = name.split(".")[0]
    if family == "F5":
        word = renumber([word[(43 * x) % 538 - 1] for x in range(1, 538)])
    first = {x for x, j in enumerate(word, 1) if j == 1}
    reference = {x for x, j in enumerate(c, 1) if j == 1}
    record = {"palindromic_defects": sum(word[x - 1] != word[537 - x] for x in range(1, 270)),
              "first_class_difference": len(first ^ reference),
              "middle_gaps": len({min(x, 538 - x) for x in range(1, 538)
                                  if min(x, 538 - x) > 236 and word[x - 1] != 6})}
    families.setdefault(family, []).append(record)
summary = {"certificate_sha256": hashlib.sha256(raw).hexdigest(),
           "class_sizes": [counts[j] for j in range(1, 7)],
           "folded_positions": 269, "family_features": {}}
for family, records in sorted(families.items()):
    summary["family_features"][family] = {"count": len(records), **{
        key: [min(r[key] for r in records), max(r[key] for r in records)] for key in records[0]}}
(out / "structure-data.json").write_text(json.dumps(summary, indent=2) + "\n")
print(json.dumps(summary, indent=2))
